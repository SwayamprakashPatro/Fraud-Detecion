#!/usr/bin/env python3
"""Write frontend/js/data.js: an offline snapshot of exactly what the API serves at /api/data.

The web UI uses the live API whenever it is served by run_app.py. The snapshot is only the
fallback for opening frontend/index.html straight from disk, or for hosting the page without Python.
Run from the project root, after training:   python tools/export_snapshot.py
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
os.chdir(ROOT)

from api.service import ModelService  # noqa: E402

svc = ModelService()
svc.load()
payload = svc.payload()
if payload["source"]["verified"] is False:
    sys.exit("The model does not reproduce outputs/logs/evaluation_report.json. Snapshot not written.")
out = os.path.join(ROOT, "frontend", "js", "data.js")
with open(out, "w") as f:
    f.write("/* Generated by tools/export_snapshot.py from the model API payload. Do not edit by hand. */\n"
            "window.GML_DATA=" + json.dumps(payload, separators=(",", ":")) + ";\n")
print("wrote", out, round(os.path.getsize(out) / 1024), "KB; verified:", payload["source"]["verified"])
